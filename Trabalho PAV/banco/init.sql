-- Inicialização do banco da API de acidentes (PostgreSQL).
-- Execute conectado ao banco definido em DATABASE_URL.
-- Pode ser executado novamente sem apagar os dados existentes.

BEGIN;

CREATE TABLE IF NOT EXISTS public.local (
    idlocal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado VARCHAR NOT NULL,
    cidade VARCHAR NOT NULL,
    bairro VARCHAR,
    rua VARCHAR
);

CREATE TABLE IF NOT EXISTS public.acidente (
    idacidente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idlocal INTEGER NOT NULL,
    data_acidente DATE NOT NULL,
    hora_acidente TIME(0) WITHOUT TIME ZONE NOT NULL,
    nome_clima VARCHAR NOT NULL,
    tipo_gravidade VARCHAR NOT NULL,
    qtd_vitimas INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT acidente_idlocal_fkey
        FOREIGN KEY (idlocal)
        REFERENCES public.local (idlocal)
        ON DELETE RESTRICT,
    CONSTRAINT ck_hora_hhmm
        CHECK (EXTRACT(SECOND FROM hora_acidente) = 0),
    CONSTRAINT ck_vitimas_nao_negativa
        CHECK (qtd_vitimas >= 0),
    CONSTRAINT ck_acidente_clima_permitido
        CHECK (
            lower(btrim(nome_clima))
            IN ('ensolarado', 'chuvoso', 'neblina', 'nublado')
        ),
    CONSTRAINT ck_acidente_gravidade_permitida
        CHECK (
            lower(btrim(tipo_gravidade))
            IN ('leve', 'moderada', 'grave', 'fatal')
        )
);

-- Compatibilidade com instalações anteriores sem a coluna de vítimas.
ALTER TABLE public.acidente
    ADD COLUMN IF NOT EXISTS qtd_vitimas INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.veiculo (
    idveiculo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idacidente INTEGER NOT NULL,
    nome_veiculo VARCHAR NOT NULL,
    CONSTRAINT veiculo_idacidente_fkey
        FOREIGN KEY (idacidente)
        REFERENCES public.acidente (idacidente)
        ON DELETE RESTRICT
);

-- Garante as restrições de negócio também em tabelas que já existiam.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_hora_hhmm'
          AND conrelid = 'public.acidente'::regclass
    ) THEN
        ALTER TABLE public.acidente
            ADD CONSTRAINT ck_hora_hhmm
            CHECK (EXTRACT(SECOND FROM hora_acidente) = 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_vitimas_nao_negativa'
          AND conrelid = 'public.acidente'::regclass
    ) THEN
        ALTER TABLE public.acidente
            ADD CONSTRAINT ck_vitimas_nao_negativa
            CHECK (qtd_vitimas >= 0);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'acidente_idlocal_fkey'
          AND conrelid = 'public.acidente'::regclass
    ) THEN
        ALTER TABLE public.acidente
            ADD CONSTRAINT acidente_idlocal_fkey
            FOREIGN KEY (idlocal)
            REFERENCES public.local (idlocal)
            ON DELETE RESTRICT;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_acidente_clima_permitido'
          AND conrelid = 'public.acidente'::regclass
    ) THEN
        ALTER TABLE public.acidente
            ADD CONSTRAINT ck_acidente_clima_permitido
            CHECK (
                lower(btrim(nome_clima))
                IN ('ensolarado', 'chuvoso', 'neblina', 'nublado')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_acidente_gravidade_permitida'
          AND conrelid = 'public.acidente'::regclass
    ) THEN
        ALTER TABLE public.acidente
            ADD CONSTRAINT ck_acidente_gravidade_permitida
            CHECK (
                lower(btrim(tipo_gravidade))
                IN ('leve', 'moderada', 'grave', 'fatal')
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'veiculo_idacidente_fkey'
          AND conrelid = 'public.veiculo'::regclass
    ) THEN
        ALTER TABLE public.veiculo
            ADD CONSTRAINT veiculo_idacidente_fkey
            FOREIGN KEY (idacidente)
            REFERENCES public.acidente (idacidente)
            ON DELETE RESTRICT;
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS idx_acidente_idlocal
    ON public.acidente (idlocal);

CREATE INDEX IF NOT EXISTS idx_veiculo_idacidente
    ON public.veiculo (idacidente);

COMMIT;